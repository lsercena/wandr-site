/**
 * Trip export utilities: PDF (jsPDF), iCalendar (.ics), Markdown clipboard,
 * and plain-text downloads — all client-side, no server dependency.
 * jsPDF is imported lazily so it never weighs down initial page loads.
 */
export interface TripExportInput {
  title: string;
  destination: string;
  duration: string;
  /** Markdown itinerary body. */
  content: string;
  /** ISO date the trip starts (defaults to today). */
  startDate?: string;
}

/** jsPDF's standard fonts are WinAnsi — map common unicode to safe glyphs. */
function sanitizeForPdf(text: string): string {
  return text
    .replace(/[\u{1F000}-\u{1FAFF}\u2600-\u27BF]/gu, '') // emoji → drop
    .replace(/[—–]/g, '-')
    .replace(/[‘’]/g, "'")
    .replace(/[“”]/g, '"')
    .replace(/…/g, '...')
    .replace(/•/g, '-')
    .replace(/ /g, ' ')
    .replace(/[^\x00-\xFF\n]/g, '');
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60) || 'itinerary';
}

function parseStartDate(startDate?: string): Date {
  const date = startDate ? new Date(`${startDate}T12:00:00`) : new Date();
  return Number.isNaN(date.getTime()) ? new Date() : date;
}

// ─── PDF ─────────────────────────────────────────────────────────────────────

export async function downloadItineraryPdf(input: TripExportInput): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 52;
  const contentWidth = pageWidth - margin * 2;
  let y = margin;

  const newPage = () => {
    doc.addPage();
    y = margin;
  };

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin) newPage();
  };

  // Header
  doc.setFont('times', 'normal');
  doc.setFontSize(22);
  doc.text(sanitizeForPdf(input.title), margin, y);
  y += 26;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(107, 94, 78);
  const meta = `${input.destination}  ·  ${input.duration}  ·  Generated by Wandr (wandrtravel-app.netlify.app)`;
  doc.text(sanitizeForPdf(meta), margin, y);
  y += 10;
  doc.setDrawColor(196, 98, 45);
  doc.setLineWidth(1);
  doc.line(margin, y, margin + contentWidth, y);
  y += 24;
  doc.setTextColor(26, 20, 16);

  // Body
  const lines = sanitizeForPdf(input.content).split('\n');
  for (const raw of lines) {
    const line = raw.trimEnd();

    if (line.trim() === '') {
      y += 7;
      continue;
    }

    const isH1 = line.startsWith('# ');
    const isH2 = line.startsWith('## ') || /^Day \d+/i.test(line);
    const isH3 = line.startsWith('### ') || /^(Morning|Afternoon|Evening):/i.test(line);
    const isBullet = /^[-•]\s+/.test(line);

    const clean = line
      .replace(/^#{1,4}\s*/, '')
      .replace(/^\*{1,2}|\*{1,2}$/g, '')
      .replace(/^[-•]\s+/, '• ');

    if (isH1) {
      ensureSpace(30);
      doc.setFont('times', 'bold');
      doc.setFontSize(16);
      y += 8;
    } else if (isH2) {
      ensureSpace(24);
      doc.setFont('times', 'bold');
      doc.setFontSize(13.5);
      y += 6;
    } else if (isH3) {
      ensureSpace(20);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
    } else {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10.5);
    }

    const wrapped = doc.splitTextToSize(clean, contentWidth - (isBullet ? 12 : 0)) as string[];
    for (const segment of wrapped) {
      ensureSpace(15);
      doc.text(segment, margin + (isBullet ? 12 : 0), y);
      y += isH1 ? 20 : isH2 ? 17 : 14.5;
    }
    y += isH1 || isH2 ? 4 : 2;
  }

  // Footer page numbers
  const pages = doc.getNumberOfPages();
  for (let p = 1; p <= pages; p++) {
    doc.setPage(p);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(150, 140, 125);
    doc.text(`Wandr · ${input.destination} itinerary · page ${p} of ${pages}`, pageWidth / 2, pageHeight - 24, {
      align: 'center',
    });
  }

  doc.save(`${slugify(input.destination)}-itinerary.pdf`);
}

// ─── iCalendar (.ics) ────────────────────────────────────────────────────────

function icsEscape(text: string): string {
  return text
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

function toIcsDate(date: Date): string {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${date.getUTCFullYear()}${pad(date.getUTCMonth() + 1)}${pad(date.getUTCDate())}`;
}

function addDays(date: Date, days: number): Date {
  const next = new Date(date);
  next.setDate(next.getDate() + days);
  return next;
}

interface IcsDay {
  day: number;
  title: string;
}

/** Extracts "Day N — title" headings; falls back to a duration estimate. */
export function extractIcsDays(input: TripExportInput): IcsDay[] {
  const re = /(?:^|\n)#{0,3}\s*\**day\s*(\d+)\s*(?:[—–:-]\s*|\s+)([^\n]*)/gi;
  const days: IcsDay[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(input.content)) !== null) {
    days.push({ day: parseInt(m[1], 10), title: m[2].replace(/[#*]/g, '').trim() || `Day ${m[1]}` });
  }
  if (days.length > 0) return days.sort((a, b) => a.day - b.day);

  // No explicit day headings — derive a count from the duration string.
  let count = 1;
  const n = input.duration.match(/(\d+)/);
  if (n) {
    count = parseInt(n[1], 10);
    if (/week/i.test(input.duration)) count *= 7;
    if (/month/i.test(input.duration)) count *= 30;
  }
  return Array.from({ length: Math.max(1, Math.min(count, 60)) }, (_, i) => ({
    day: i + 1,
    title: `Day ${i + 1} — ${input.destination}`,
  }));
}

export function buildItineraryIcs(input: TripExportInput): string {
  const start = parseStartDate(input.startDate);
  const days = extractIcsDays(input);
  const stamp = new Date().toISOString().replace(/[-:]/g, '').replace(/\.\d{3}/, '');

  const events = days.map((d) => {
    const eventStart = addDays(start, d.day - 1);
    const eventEnd = addDays(eventStart, 1);
    return [
      'BEGIN:VEVENT',
      `UID:${slugify(input.destination)}-day${d.day}-${stamp}@wandr`,
      `DTSTAMP:${stamp}`,
      `DTSTART;VALUE=DATE:${toIcsDate(eventStart)}`,
      `DTEND;VALUE=DATE:${toIcsDate(eventEnd)}`,
      `SUMMARY:${icsEscape(`${input.title} — Day ${d.day}: ${d.title}`)}`,
      `DESCRIPTION:${icsEscape(`Generated by Wandr. Trip: ${input.title}`)}`,
      'END:VEVENT',
    ].join('\r\n');
  });

  return [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Wandr//AI Travel Planner//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    ...events,
    'END:VCALENDAR',
  ].join('\r\n');
}

export function downloadItineraryIcs(input: TripExportInput): void {
  const ics = buildItineraryIcs(input);
  const stamp = toIcsDate(parseStartDate(input.startDate));
  downloadTextFile(`${slugify(input.destination)}-itinerary-${stamp}.ics`, 'text/calendar;charset=utf-8', ics);
}

// ─── Generic helpers ─────────────────────────────────────────────────────────

export function downloadTextFile(filename: string, mime: string, text: string): void {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  // Give the browser a tick before revoking (Firefox needs the delay).
  window.setTimeout(() => URL.revokeObjectURL(url), 1500);
}

export async function copyTextToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    try {
      const ta = document.createElement('textarea');
      ta.value = text;
      ta.style.position = 'fixed';
      ta.style.opacity = '0';
      document.body.appendChild(ta);
      ta.select();
      const ok = document.execCommand('copy');
      ta.remove();
      return ok;
    } catch {
      return false;
    }
  }
}
