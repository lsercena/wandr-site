export function getCountryBySlug(slug: string): Country | undefined {
  return countries.find((c) => c.slug === slug);
}

export function getCountriesByFilter(key: string, value?: string): Country[] {
  switch (key) {
    case 'digital-nomad':
      return countries.filter((c) => c.digitalNomadVisa.available).sort((a, b) => b.overview.digitalNomadScore - a.overview.digitalNomadScore);
    case 'cheapest':
      return [...countries].sort((a, b) => a.costOfLiving.index - b.costOfLiving.index);
    case 'safest':
      return [...countries].sort((a, b) => b.overview.safetyScore - a.overview.safetyScore);
    case 'fastest-internet':
      return [...countries].sort((a, b) => b.remoteWork.internetSpeed.download - a.remoteWork.internetSpeed.download);
    case 'visa-free':
      return countries.filter((c) => c.visa.visaFree);
    case 'lowest-taxes':
      return countries.filter((c) => c.tax.zeroIncomeTax || c.tax.territorialTax);
    case 'best-healthcare':
      return [...countries].sort((a, b) => b.healthcare.englishSpeakingDoctors - a.healthcare.englishSpeakingDoctors);
    case 'nomad-destinations':
      return countries.filter((c) => c.overview.digitalNomadScore >= 80).sort((a, b) => b.overview.digitalNomadScore - a.overview.digitalNomadScore);
    case 'nationality':
      if (value) return countries.filter((c) => c.visa.visaFreeFor?.includes(value));
      return countries;
    default:
      return countries;
  }
}

